"""Render the README pixel-art panels from plain-text sources.

Every branding/readme/src/*.txt file describes one panel (format: branding/readme/README.md) and
becomes branding/readme/<name>.svg, drawn in the website's pixel language: the Scan R1 bitmap
fonts, stepped corners, a hard drop shadow, dotted rules and the site's flat colour tokens.

    python3 tools/readme_art.py            render everything
    python3 tools/readme_art.py --watch    re-render whenever a source file changes
    python3 tools/readme_art.py --check    exit 1 if a rendered SVG is out of date (CI)

Only the standard library is used.
"""

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "branding" / "readme" / "src"
OUT = ROOT / "branding" / "readme"
DATA = Path(__file__).resolve().parent / "readme_art_data"

# Colour tokens from the website (tokens.css / gfx.ts), nothing else.
CANVAS, SURFACE, DIVIDER = "#0d1010", "#141918", "#384543"
TEXT, SECONDARY, MUTED, ACCENT = "#f1eee5", "#cad0ca", "#8c9690", "#58b9b0"
DROP = "#1f3d3a"
SPRITE = {
    "0": "#2a3540", "1": "#3d4c5a", "2": "#5a6c7c", "3": "#8496a6",
    "4": "#121716", "5": "#1d2422", "6": "#27312f", "7": "#384543",
    "a": "#8c9690", "b": "#cad0ca", "c": "#f1eee5", "g": "#1d2422", "h": "#384543",
    "Q": "#cad0ca", "P": "#f1eee5", "I": "#0d1010", "L": "#a9b6a4",
    "k": "#1a211f", "K": "#2b3633", "T": "#58b9b0",
}

U = 2            # one art pixel, in SVG units; every size below is a multiple of it
WIDTH = 760
MARGIN = 6 * U   # canvas around the panel
DROP_OFFSET = 3 * U
PAD = 12 * U     # panel padding
NOTCH = (U, 2 * U)  # the lockup's stepped corner (n1, n2)

FONTS = json.loads((DATA / "fonts.json").read_text(encoding="utf-8"))
SPRITES = json.loads((DATA / "sprites.json").read_text(encoding="utf-8"))


class SourceError(Exception):
    pass


class Svg:
    def __init__(self):
        self.paths = {}
        self.z = 0  # paint layer: 0 is the panel, 1 is everything drawn on it

    def rect(self, x, y, w, h, color):
        if w > 0 and h > 0:
            self.paths.setdefault((self.z, color), []).append("M%g %gh%gv%gh%gz" % (x, y, w, h, -w))

    def notched(self, x, y, w, h, color):
        """A rectangle with the website's two-step corner, as three overlapping rects."""
        n1, n2 = NOTCH
        self.rect(x + n2, y, w - 2 * n2, h, color)
        self.rect(x + n1, y + n1, w - 2 * n1, h - 2 * n1, color)
        self.rect(x, y + n2, w, h - 2 * n2, color)

    def frame(self, x, y, w, h):
        self.notched(x + DROP_OFFSET, y + DROP_OFFSET, w, h, DROP)
        self.notched(x, y, w, h, DIVIDER)
        self.notched(x + U, y + U, w - 2 * U, h - 2 * U, SURFACE)

    def dotted(self, x, y, w):
        for dx in range(0, w, 4 * U):
            self.rect(x + dx, y, min(2 * U, w - dx), U, DIVIDER)

    def render(self, width, height, title, desc):
        out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" '
               'role="img" aria-labelledby="t d" shape-rendering="crispEdges">' % (width, height, width, height),
               "  <title id=\"t\">%s</title>" % esc(title), "  <desc id=\"d\">%s</desc>" % esc(desc),
               "  <!-- Generated by tools/readme_art.py from branding/readme/src. Do not edit by hand. -->",
               '  <rect width="%d" height="%d" fill="%s"/>' % (width, height, CANVAS)]
        for (_, color), segs in sorted(self.paths.items(), key=lambda kv: kv[0][0]):
            out.append('  <path fill="%s" d="%s"/>' % (color, "".join(segs)))
        out.append("</svg>")
        return "\n".join(out) + "\n"


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def glyph(font, ch):
    g = FONTS[font]["glyphs"].get(str(ord(ch)))
    if g is None:
        raise SourceError("character %r is not available in the pixel font" % ch)
    return g


def width_of(font, s, scale):
    return sum(glyph(font, ch)[0] for ch in s) * scale


def cap_height(font):
    adv, xo, w, bits = glyph(font, "H")
    h = FONTS[font]["height"]
    return sum(1 for r in range(h) if "1" in bits[r * w:(r + 1) * w])


def text(svg, x, baseline, s, font, scale, color, shadow=False):
    """Draw s with the left edge at x and the baseline at `baseline`."""
    f = FONTS[font]
    top = baseline + f["top"] * scale
    for dx, dy, c in (((scale, scale, DROP),) if shadow else ()) + ((0, 0, color),):
        pen = x
        for ch in s:
            adv, xo, w, bits = glyph(font, ch)
            for r in range(f["height"]):
                row, c0 = bits[r * w:(r + 1) * w] if w else "", 0
                while c0 < len(row):
                    if row[c0] == "1":
                        start = c0
                        while c0 < len(row) and row[c0] == "1":
                            c0 += 1
                        svg.rect(pen + dx + (xo + start) * scale, top + dy + r * scale, (c0 - start) * scale, scale, c)
                    else:
                        c0 += 1
            pen += adv * scale


def wrap(s, font, scale, width):
    lines, cur = [], ""
    for word in s.split():
        trial = (cur + " " + word).strip()
        if cur and width_of(font, trial, scale) > width:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines


def sprite(svg, name, x, y, scale):
    data = SPRITES.get(name)
    if data is None:
        raise SourceError("unknown sprite %r (available: %s)" % (name, ", ".join(SPRITES)))
    for ry, row in enumerate(data["rows"]):
        rx = 0
        while rx < len(row):
            code = row[rx]
            if code == ".":
                rx += 1
                continue
            start = rx
            while rx < len(row) and row[rx] == code:
                rx += 1
            svg.rect(x + start * scale, y + ry * scale, (rx - start) * scale, scale, SPRITE.get(code, "#ff00ff"))
    return data["width"] * scale, data["height"] * scale


def parse(path):
    """`key: value` lines. `row:` lines repeat; the others are single settings."""
    settings, rows = {}, []
    for n, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            raise SourceError("%s line %d: expected 'key: value'" % (path.name, n))
        key, value = (p.strip() for p in line.split(":", 1))
        if key == "row":
            cells = [c.strip() for c in value.split("|")]
            if len(cells) != 2:
                raise SourceError("%s line %d: a row needs 'name | value'" % (path.name, n))
            rows.append(cells)
        else:
            settings[key] = value
    return settings, rows


def compose(svg, settings, rows):
    """Lay the panel out onto svg and return the panel height. Run once to measure, once to paint."""
    heads = [c.strip() for c in settings["columns"].split("|")]
    if len(heads) != 2:
        raise SourceError("'columns' needs 'Left | Right'")
    px, py = MARGIN, MARGIN
    pw = WIDTH - 2 * MARGIN - DROP_OFFSET
    inner_x, inner_w = px + PAD, pw - 2 * PAD
    sprite_name = settings.get("sprite")
    if sprite_name and sprite_name not in SPRITES:
        raise SourceError("unknown sprite %r (available: %s)" % (sprite_name, ", ".join(SPRITES)))
    sc = int(settings.get("sprite_scale", U))
    art_w = SPRITES[sprite_name]["width"] * sc if sprite_name else 0
    art_h = SPRITES[sprite_name]["height"] * sc if sprite_name else 0
    col_w = inner_w - (art_w + 2 * PAD if art_w else 0)

    svg.z = 1
    y = py + PAD
    ts = 3  # the panel title is the site's .px-sub at three art pixels
    text(svg, inner_x, y - FONTS["bold"]["top"] * ts, settings["title"], "bold", ts, TEXT, shadow=True)
    y += FONTS["bold"]["height"] * ts + PAD
    for line in wrap(settings["intro"], "sans", U, col_w):
        text(svg, inner_x, y + cap_height("sans") * U, line, "sans", U, SECONDARY)
        y += 16 * U
    y += PAD
    for i, head in enumerate(heads):
        head = head.upper()
        hx = inner_x if i == 0 else inner_x + col_w - width_of("mono", head, U)
        text(svg, hx, y + cap_height("mono") * U, head, "mono", U, MUTED)
    y += 7 * U + 4 * U
    svg.dotted(inner_x, y, col_w)
    row_h = 26 * U
    for left, right in rows:
        if width_of("sans", left, U) + 4 * PAD > col_w - width_of("mono", right, U):
            raise SourceError("row %r is too long for its value; shorten it" % left)
        cy = y + row_h // 2
        text(svg, inner_x, cy + cap_height("sans") * U // 2, left, "sans", U, TEXT)
        text(svg, inner_x + col_w - width_of("mono", right, U), cy + cap_height("mono") * U // 2, right, "mono", U, MUTED)
        y += row_h
        svg.dotted(inner_x, y, col_w)
    y += PAD
    if art_w:
        ay = py + (y - py - art_h) // 2
        sprite(svg, sprite_name, inner_x + inner_w - art_w, ay, sc)
        y = max(y, ay + art_h + PAD)
    svg.z = 0
    return px, py, pw, y - py


def build_svg(path):
    settings, rows = parse(path)
    for key in ("title", "intro", "columns"):
        if key not in settings:
            raise SourceError("%s: missing '%s'" % (path.name, key))
    try:
        _, _, _, ph = compose(Svg(), settings, rows)
        svg = Svg()
        px, py, pw, ph = compose(svg, settings, rows)
    except SourceError as e:
        raise SourceError("%s: %s" % (path.name, e))
    svg.frame(px, py, pw, ph)
    height = py + ph + DROP_OFFSET + MARGIN
    return svg.render(WIDTH, height, settings["title"], "; ".join(r[0] for r in rows))


def build(check):
    stale = []
    for path in sorted(SRC.glob("*.txt")):
        target = OUT / (path.stem + ".svg")
        text_ = build_svg(path)
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != text_:
            stale.append(target.name)
            if not check:
                target.write_text(text_, encoding="utf-8")
    return stale


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--watch", action="store_true", help="re-render when a source file changes")
    ap.add_argument("--check", action="store_true", help="exit 1 if a rendered SVG is out of date")
    args = ap.parse_args()

    def run_once(check):
        try:
            return build(check)
        except SourceError as e:
            print("error:", e, file=sys.stderr)
            return None

    if args.watch:
        seen = None
        print("watching %s (Ctrl+C to stop)" % SRC.relative_to(ROOT))
        while True:
            stamp = tuple((p.name, p.stat().st_mtime_ns) for p in sorted(SRC.glob("*.txt")))
            if stamp != seen:
                seen = stamp
                stale = run_once(False)
                if stale:
                    print("updated:", ", ".join(stale))
            time.sleep(0.5)
    stale = run_once(args.check)
    if stale is None:
        return 1
    if args.check and stale:
        print("out of date (run python3 tools/readme_art.py):", ", ".join(stale), file=sys.stderr)
        return 1
    print("updated: " + ", ".join(stale) if stale else "up to date")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        pass
