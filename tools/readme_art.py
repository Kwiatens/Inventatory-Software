"""Render the README pixel-art sections from plain-text sources.

Every branding/readme/src/*.txt file describes one section (format: branding/readme/README.md) and
becomes branding/readme/<name>.svg plus <name>-light.svg for light page themes, drawn in the
website's pixel language: the Scan R1 bitmap fonts, a hard drop shadow, dotted rules and the
site's flat colour tokens, on a transparent background.

    python3 tools/readme_art.py            render everything
    python3 tools/readme_art.py --watch    re-render whenever a source file changes
    python3 tools/readme_art.py --check    exit 1 if a rendered SVG is out of date (CI)

Only the standard library is used.
"""

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "branding" / "readme" / "src"
OUT = ROOT / "branding" / "readme"
DATA = Path(__file__).resolve().parent / "readme_art_data"

# Colour tokens from the website's tokens.css. Light swaps only the ink, for white pages.
THEMES = {
    "": {"text": "#f1eee5", "muted": "#8c9690", "rule": "#384543", "drop": "#1f3d3a"},
    "-light": {"text": "#0d1010", "muted": "#5d6865", "rule": "#cad0ca", "drop": "#cad0ca"},
}

U = 2            # one art pixel, in SVG units; every size below is a multiple of it
WIDTH = 830      # the README column
PAD = 12 * U

FONTS = json.loads((DATA / "fonts.json").read_text(encoding="utf-8"))


class SourceError(Exception):
    pass


class Svg:
    def __init__(self, theme):
        self.theme = theme
        self.paths = {}

    def rect(self, x, y, w, h, color):
        if w > 0 and h > 0:
            self.paths.setdefault(color, []).append("M%g %gh%gv%gh%gz" % (x, y, w, h, -w))

    def dotted(self, x, y, w):
        for dx in range(0, w, 4 * U):
            self.rect(x + dx, y, min(2 * U, w - dx), U, self.theme["rule"])

    def render(self, width, height, title, desc):
        out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" '
               'role="img" aria-labelledby="t d" shape-rendering="crispEdges">' % (width, height, width, height),
               "  <title id=\"t\">%s</title>" % esc(title), "  <desc id=\"d\">%s</desc>" % esc(desc),
               "  <!-- Generated by tools/readme_art.py from branding/readme/src. Do not edit by hand. -->"]
        for color, segs in self.paths.items():
            out.append('  <path fill="%s" d="%s"/>' % (color, "".join(segs)))
        out.append("</svg>")
        return "\n".join(out) + "\n"


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def glyph(font, ch):
    g = FONTS[font]["glyphs"].get(str(ord(ch)))
    if g is None:
        raise SourceError("character %r is not available in the pixel font" % ch)
    return g


def width_of(font, s, scale):
    return sum(glyph(font, ch)[0] for ch in s) * scale


def cap_height(font):
    adv, xo, w, bits = glyph(font, "H")
    h = FONTS[font]["height"]
    return sum(1 for r in range(h) if "1" in bits[r * w:(r + 1) * w])


def text(svg, x, baseline, s, font, scale, color, shadow=None):
    """Draw s with the left edge at x and the baseline at `baseline`."""
    f = FONTS[font]
    top = baseline + f["top"] * scale
    for dx, dy, c in (((scale, scale, shadow),) if shadow else ()) + ((0, 0, color),):
        pen = x
        for ch in s:
            adv, xo, w, bits = glyph(font, ch)
            for r in range(f["height"]):
                row, c0 = bits[r * w:(r + 1) * w] if w else "", 0
                while c0 < len(row):
                    if row[c0] == "1":
                        start = c0
                        while c0 < len(row) and row[c0] == "1":
                            c0 += 1
                        svg.rect(pen + dx + (xo + start) * scale, top + dy + r * scale, (c0 - start) * scale, scale, c)
                    else:
                        c0 += 1
            pen += adv * scale


def wrap(s, font, scale, width):
    lines, cur = [], ""
    for word in s.split():
        trial = (cur + " " + word).strip()
        if cur and width_of(font, trial, scale) > width:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines


def parse(path):
    """`key: value` lines. `row:` lines repeat; the others are single settings."""
    settings, rows = {}, []
    for n, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            raise SourceError("%s line %d: expected 'key: value'" % (path.name, n))
        key, value = (p.strip() for p in line.split(":", 1))
        if key == "row":
            cells = [c.strip() for c in value.split("|")]
            if len(cells) != 2:
                raise SourceError("%s line %d: a row needs 'name | value'" % (path.name, n))
            rows.append(cells)
        else:
            settings[key] = value
    return settings, rows


def compose(svg, settings, rows):
    """Lay the section out onto svg and return its height."""
    t = svg.theme
    x, w = 2 * U, WIDTH - 4 * U
    desc_x = x + max(width_of("sans", name, U) for name, _ in rows) + 16 * U
    y = 0
    ts = 2  # the section title, set like the site's .px-sub
    text(svg, x, y + (-FONTS["bold"]["top"]) * ts, settings["title"], "bold", ts, t["text"], shadow=t["drop"])
    y += FONTS["bold"]["height"] * ts + PAD // 2
    svg.dotted(x, y, w)
    row_h = 24 * U
    cap = cap_height("sans") * U
    for name, desc in rows:
        if desc_x + width_of("sans", desc, U) > x + w:
            raise SourceError("row %r is too long for the width; shorten it" % name)
        base = y + row_h // 2 + cap // 2
        text(svg, x, base, name, "sans", U, t["text"])
        text(svg, desc_x, base, desc, "sans", U, t["muted"])
        y += row_h
        svg.dotted(x, y, w)
    return y + U + 2 * U


def build_svg(path, theme):
    settings, rows = parse(path)
    if "title" not in settings or not rows:
        raise SourceError("%s: needs a 'title' and at least one 'row'" % path.name)
    svg = Svg(theme)
    try:
        height = compose(svg, settings, rows)
    except SourceError as e:
        raise SourceError("%s: %s" % (path.name, e))
    return svg.render(WIDTH, height, settings["title"], "; ".join(r[0] for r in rows))


def build(check):
    stale = []
    for path in sorted(SRC.glob("*.txt")):
        for suffix, theme in THEMES.items():
            target = OUT / (path.stem + suffix + ".svg")
            text_ = build_svg(path, theme)
            current = target.read_text(encoding="utf-8") if target.exists() else None
            if current != text_:
                stale.append(target.name)
                if not check:
                    target.write_text(text_, encoding="utf-8")
    return stale


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--watch", action="store_true", help="re-render when a source file changes")
    ap.add_argument("--check", action="store_true", help="exit 1 if a rendered SVG is out of date")
    args = ap.parse_args()

    def run_once(check):
        try:
            return build(check)
        except SourceError as e:
            print("error:", e, file=sys.stderr)
            return None

    if args.watch:
        seen = None
        print("watching %s (Ctrl+C to stop)" % SRC.relative_to(ROOT))
        while True:
            stamp = tuple((p.name, p.stat().st_mtime_ns) for p in sorted(SRC.glob("*.txt")))
            if stamp != seen:
                seen = stamp
                stale = run_once(False)
                if stale:
                    print("updated:", ", ".join(stale))
            time.sleep(0.5)
    stale = run_once(args.check)
    if stale is None:
        return 1
    if args.check and stale:
        print("out of date (run python3 tools/readme_art.py):", ", ".join(stale), file=sys.stderr)
        return 1
    print("updated: " + ", ".join(stale) if stale else "up to date")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        pass
